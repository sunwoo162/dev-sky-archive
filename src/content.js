export function findIsland(id) {
  return islands.find((island) => island.id === id) ?? islands[0];
}

export function findProject(projectId) {
  for (const island of islands) {
    const found = island.projects.find((item) => item.id === projectId);
    if (found) return { project: found, island };
  }
  return { project: islands[0].projects[0], island: islands[0] };
}
